/** Russian plural: 1 файл / 2 файла / 5 файлов. */
function pl(count: number, one: string, few: string, many: string): string {
  const m10 = count % 10;
  const m100 = count % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}

